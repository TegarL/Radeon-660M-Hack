#!/usr/bin/env python3
"""Generate the accelerator's MMHUB table from AMD's Linux v6.17 register headers."""
from pathlib import Path
import re
import argparse
import hashlib
import json
import urllib.request

ROOT = Path(__file__).resolve().parents[1]
HEADERS = ROOT / 'build/linux-v6.17'
OUTPUT = ROOT / 'src/RembrandtGfx/vcn_vm_table.hpp'


def registers(version):
    text = (HEADERS / f'mmhub_{version}_offset.h').read_text()
    return {m.group(1): int(m.group(2), 16) for m in re.finditer(
        r'^#define\s+(mm\w+)\s+(0x[0-9a-fA-F]+)\s*$', text, re.M)}


def names_in_apple_order():
    # AMDMMHub_2_0_0::fillVMRegisters, 25G332: 12 globals, 16 contexts, 18 invalidators.
    names = ['mmMMMC_VM_MX_L1_TLB_CNTL']
    names += ['mmMMVM_' + name for name in [
        'L2_CNTL', 'L2_CNTL2', 'L2_CNTL3', 'L2_CNTL4', 'L2_PROTECTION_FAULT_CNTL',
        'L2_PROTECTION_FAULT_CNTL2', 'L2_PROTECTION_FAULT_MM_CNTL3',
        'L2_PROTECTION_FAULT_MM_CNTL4', 'L2_PROTECTION_FAULT_STATUS',
        'L2_PROTECTION_FAULT_ADDR_LO32', 'L2_PROTECTION_FAULT_ADDR_HI32']]
    for i in range(16):
        names += [f'mmMMVM_CONTEXT{i}_' + name for name in [
            'PAGE_TABLE_BASE_ADDR_LO32', 'PAGE_TABLE_BASE_ADDR_HI32',
            'PAGE_TABLE_START_ADDR_LO32', 'PAGE_TABLE_START_ADDR_HI32',
            'PAGE_TABLE_END_ADDR_LO32', 'PAGE_TABLE_END_ADDR_HI32', 'CNTL']]
    for i in range(18):
        names += [f'mmMMVM_INVALIDATE_ENG{i}_' + name for name in [
            'ADDR_RANGE_LO32', 'ADDR_RANGE_HI32', 'REQ', 'ACK', 'SEM']]
    assert len(names) == 214
    return names


def main():
    global HEADERS, OUTPUT
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--headers-dir', type=Path, default=HEADERS, help='local header directory; missing pinned headers are downloaded here')
    parser.add_argument('--output', type=Path, default=OUTPUT)
    args = parser.parse_args()
    HEADERS, OUTPUT = args.headers_dir, args.output
    HEADERS.mkdir(parents=True, exist_ok=True)
    lock = json.loads((ROOT / 'source-lock.json').read_text())['vcn_vm_table']
    for name, spec in lock['headers'].items():
        path = HEADERS / name
        if not path.exists():
            with urllib.request.urlopen(spec['url'], timeout=60) as response:
                path.write_bytes(response.read())
        if hashlib.sha256(path.read_bytes()).hexdigest() != spec['sha256']:
            raise ValueError(f'{name} does not match the recorded Linux v6.17 header')
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    old, new = registers('2_0_0'), registers('2_3_0')
    licence = (HEADERS / 'mmhub_2_3_0_offset.h').read_text().split('*/', 1)[0] + '*/\n'
    lines = [licence, '#pragma once', '// Generated by generate_vcn_vm_table.py; do not edit.',
             'struct VcnVmRegister { uint32_t oldOffset, newOffset; };',
             'static constexpr VcnVmRegister VcnVmRegisters[] {']
    for name in names_in_apple_order():
        lines.append(f'    {{0x{old[name]:x}, 0x{new[name]:x}}}, // {name}')
    lines += ['};', 'static constexpr size_t VcnVmRegisterCount = 214;']
    OUTPUT.write_text('\n'.join(lines) + '\n')
    if hashlib.sha256(OUTPUT.read_bytes()).hexdigest() != lock['generated_sha256']:
        raise ValueError('Generated table differs from the exported candidate 23 table')
    print(f'Generated {OUTPUT}: 214 register pairs; matches candidate 23')


if __name__ == '__main__':
    main()
